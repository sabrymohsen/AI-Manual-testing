import { prisma } from "@/lib/db"
import { withBugModule } from "@/lib/bug-reports/module"
import { chromium, Page, Browser, BrowserContext } from "playwright"
import { ExecutionPlanItem, ExecutionStepPlan, BrainMetrics } from "./types"
import {
  resolveLocatorFromMemory,
  recordSuccessfulLocator,
  recordFailedLocator
} from "./memory"
import { executeStep } from "../playwright/step-executor"
import { decryptSecret } from "../crypto"
import { handleLogin } from "../playwright/login-handler"
import { saveFile } from "../storage"
import { isAgentBrainCancelSignalSet } from "@/lib/queue"
import { nextBugKey } from "@/lib/bug-reports/keys"

export interface AgentExecutionOptions {
  agentBrainRunId: string
  projectId: string
  safetyDoNotDelete: boolean
  safetyDoNotModify: boolean
}

export async function runExecutionPlan(
  planItems: ExecutionPlanItem[],
  options: AgentExecutionOptions
): Promise<BrainMetrics> {
  const { agentBrainRunId, projectId, safetyDoNotDelete, safetyDoNotModify } = options

  console.log(`[AgentExecutor] Starting execution plan for project ${projectId}, run: ${agentBrainRunId}`)

  let browser: Browser | null = null
  let context: BrowserContext | null = null
  let page: Page | null = null

  // Performance telemetry counters
  let totalStepDurationMs = 0
  let totalStepsCount = 0
  let totalLocatorResolutionMs = 0
  let totalMemoryLookupMs = 0
  let totalHealed = 0
  let totalFail = 0
  let totalPass = 0

  const project = await prisma.project.findUnique({
    where: { id: projectId },
    include: { credentials: true }
  })

  if (!project) throw new Error("Project not found")

  try {
    browser = await chromium.launch({ headless: true })
    context = await browser.newContext({
      viewport: { width: 1280, height: 800 }
    })
    page = await context.newPage()

    for (const item of planItems) {
      // Check cancellation signal between scenarios
      if (await isAgentBrainCancelSignalSet(agentBrainRunId)) {
        console.warn(`[AgentExecutor] Cancellation signal set for run ${agentBrainRunId}. Aborting execution plan.`);
        break;
      }
      console.log(`[AgentExecutor] Running scenario: ${item.testName}`)

      // 1. Create TestCase in DB linked to agentBrainRun
      let credentialId: string | null = null
      if (project.credentials.length > 0) {
        const cred = project.credentials.find(c => c.roleName.toLowerCase() === item.role.toLowerCase()) || project.credentials[0]
        credentialId = cred.id
      }

      const dbTestCase = await prisma.testCase.create({
        data: {
          title: `[Brain] ${item.testName}`,
          preconditions: "Generated by Agent Brain Planner.",
          priority: item.priority === "Critical" ? "High" : item.priority,
          source: "AIGenerated",
          projectId,
          requiredCredentialId: credentialId,
          steps: {
            createMany: {
              data: item.steps.map((s, idx) => ({
                stepNumber: idx + 1,
                actionDescription: s.actionDescription,
                expectedResult: s.expectedResult,
                actionType: s.actionType as any,
                targetType: s.targetType as any,
                targetValue: s.targetValue,
                inputValue: s.inputValue || ""
              }))
            }
          }
        }
      })

      // 2. Create TestRun in DB
      let viewportWidth = 1280
      let viewportHeight = 800
      const dbTestRun = await prisma.testRun.create({
        data: {
          projectId,
          testCaseId: dbTestCase.id,
          credentialId,
          status: "Running",
          browserType: project.browserType,
          viewport: project.viewport,
          viewportWidth,
          viewportHeight,
          triggeredBy: "AIGenerated",
          executionMode: "SelfHealing",
          agentBrainRunId,
          startedAt: new Date()
        }
      })

      // Log array
      const stepResults: any[] = []

      // 3. Navigate to url / handle login if credential role matches
      if (credentialId) {
        const cred = project.credentials.find(c => c.id === credentialId)!
        const password = decryptSecret({
          encrypted: cred.encryptedPassword,
          iv: cred.encryptionIv,
          authTag: cred.encryptionAuthTag,
          keyVersion: cred.keyVersion,
        })
        const loginUrl = cred.loginUrl || project.webAppUrl
        try {
          await handleLogin(page, { url: loginUrl, username: cred.username, password })
        } catch (e: any) {
          console.warn("[AgentExecutor] Credentials login failed:", e.message)
        }
      } else {
        await page.goto(project.webAppUrl).catch(() => {})
      }

      // 4. Step Execution Loop
      for (const step of item.steps) {
        totalStepsCount++
        const stepStart = performance.now()

        console.log(`[AgentExecutor] Executing Step: ${step.actionDescription}`)

        // A. Sandbox Safety Guard check
        let isBlocked = false
        if (safetyDoNotDelete) {
          const destructiveRegexp = /\b(delete|destroy|wipe|purge|pay|purchase|payment|terminate_account|cancel_account)\b/i
          const checkStr = `${step.actionDescription} ${step.actionType} ${step.targetValue || ""} ${step.inputValue || ""}`
          if (destructiveRegexp.test(checkStr)) {
            isBlocked = true
          }
        }

        if (isBlocked) {
          console.warn(`[AgentExecutor] Safety sandbox blocked step: ${step.actionDescription}`)
          stepResults.push({
            stepNumber: stepResults.length + 1,
            actionDescription: step.actionDescription,
            expectedResult: step.expectedResult,
            status: "Skipped",
            actualResult: "Skipped for safety (sandbox filter matched).",
            errorDetails: "Safety block active."
          })
          continue
        }

        // B. Locator Resolution Layer (Memory lookup target <10ms)
        let resolvedSelector: string | null = null
        if (step.targetValue) {
          const memRes = await resolveLocatorFromMemory(projectId, step.targetValue)
          resolvedSelector = memRes.resolved
          totalMemoryLookupMs += memRes.lookupMs
        }

        // Measure locator resolution (resolution speed check target <50ms)
        const resolutionStart = performance.now()
        const targetValueToUse = resolvedSelector || step.targetValue
        totalLocatorResolutionMs += (performance.now() - resolutionStart)

        // C. Playwright execution
        let status: "Passed" | "Failed" | "SelfHealed" = "Passed"
        let actualResult = "Step completed successfully"
        let errorDetails: string | null = null
        let healingLogs: string | null = null

        try {
          // Execute the step using standard runner helper
          await executeStep(page, {
            actionType: step.actionType,
            targetType: resolvedSelector ? "css" : step.targetType,
            targetValue: targetValueToUse,
            inputValue: step.inputValue || "",
            timeoutMs: 8000
          })

          // On success, update locator memory
          if (step.targetValue) {
            await recordSuccessfulLocator(projectId, step.targetValue, targetValueToUse)
          }
          totalPass++
        } catch (err: any) {
          console.warn(`[AgentExecutor] Step failed: "${step.actionDescription}". Triggering self-healing...`)
          
          // Self-Healing Strategy (Layer 4 fallback)
          totalHealed++
          const healingStart = performance.now()
          
          // Attempt simple healing: Try finding text contents, or fallback CSS patterns
          let healingSuccess = false
          let healedSelector = ""
          
          if (step.actionType === "click" && step.targetType === "css") {
            // healing alternative check: text matching
            try {
              const textSelector = `text="${step.actionDescription.replace(/click\s+/i, "")}"`
              await page.click(textSelector, { timeout: 3000 })
              healedSelector = textSelector
              healingSuccess = true
            } catch {}
          }

          if (healingSuccess) {
            status = "SelfHealed"
            actualResult = "Healed using semantic fallback locator."
            healingLogs = `Healed step in ${(performance.now() - healingStart).toFixed(1)}ms. Fallback selector used: ${healedSelector}`
            
            // Record successful heal in memory
            if (step.targetValue) {
              await recordSuccessfulLocator(projectId, step.targetValue, healedSelector)
            }
            totalPass++
          } else {
            // Execution fully failed
            status = "Failed"
            errorDetails = err.message || "Element selector timeout or page navigation failure."
            actualResult = "Step execution failed."
            totalFail++

            // Record failed locator in memory
            if (step.targetValue) {
              await recordFailedLocator(projectId, step.targetValue, targetValueToUse)
            }
          }
        }

        const stepDuration = performance.now() - stepStart
        totalStepDurationMs += stepDuration

        // Capture evidence screenshot
        let screenshotPath: string | null = null
        try {
          const scr = await page.screenshot({ type: "png", timeout: 4000 })
          screenshotPath = await saveFile("screenshots", `agent-brain-step-${totalStepsCount}.png`, scr)
        } catch {}

        // Save step result to DB
        const dbStepResult = await prisma.testStepResult.create({
          data: {
            testRunId: dbTestRun.id,
            stepNumber: stepResults.length + 1,
            actionDescription: step.actionDescription,
            expectedResult: step.expectedResult,
            actualResult,
            status,
            errorDetails,
            notes: healingLogs,
            screenshotAfter: screenshotPath
          }
        })

        stepResults.push({
          id: dbStepResult.id,
          stepNumber: dbStepResult.stepNumber,
          actionDescription: step.actionDescription,
          expectedResult: step.expectedResult,
          status,
          errorDetails,
          screenshotPath
        })

        // If step failed, generate a Bug Report immediately and stop scenario
        if (status === "Failed") {
          await prisma.bugReport.create({
            data: await withBugModule({
              title: `[Agent Defect] Scenario failed at step ${stepResults.length}: ${step.actionDescription}`,
              severity: "High",
              priority: "High",
              status: "Open",
              projectId,
              bugKey: await nextBugKey(projectId),
              testCaseId: dbTestCase.id,
              testRunId: dbTestRun.id,
              testStepResultId: dbStepResult.id,
              stepsToReproduce: `1. Run agent brain scenario "${item.testName}"\n2. Reached step ${stepResults.length}: "${step.actionDescription}"\n3. Observed error: ${errorDetails}`,
              expectedResult: step.expectedResult,
              actualResult: "Execution failed to find element or complete action.",
              screenshotPath,
              agentBrainRunId
            })
          })
          break
        }
      }

      // Complete TestRun
      const testRunStatus = stepResults.some(s => s.status === "Failed") ? "Failed" : "Passed"
      await prisma.testRun.update({
        where: { id: dbTestRun.id },
        data: {
          status: testRunStatus,
          completedAt: new Date(),
          durationMs: Math.floor(stepResults.reduce((acc, cur) => acc + (cur.durationMs || 0), 0))
        }
      })
    }
  } finally {
    if (context) await context.close()
    if (browser) await browser.close()
  }

  // Build metrics
  return {
    planningDurationMs: 0, // Filled in worker
    averageStepDurationMs: totalStepsCount > 0 ? Math.floor(totalStepDurationMs / totalStepsCount) : 0,
    locatorResolutionMs: totalStepsCount > 0 ? Math.floor(totalLocatorResolutionMs / totalStepsCount) : 0,
    memoryLookupMs: totalStepsCount > 0 ? Math.floor(totalMemoryLookupMs / totalStepsCount) : 0
  }
}
