// Shared Test Studio run pipeline: writes the script into the SHAFT maven
// workspace, spawns the Maven run in the background, streams logs into the
// TestExecution row, and harvests evidence on completion.
// Used by POST /api/hub/scripts/{id}/run and by the AI Agent's run_test tool.

import { prisma } from "@/lib/db"
import { spawn } from "child_process"
import * as fs from "fs"
import * as path from "path"
import { harvestEvidence, extractTargetUrl, MAVEN_PROJECT_PATH } from "@/lib/hub-evidence"
import { parseAndStoreAccessibility } from "@/lib/hub-accessibility"

const JAVA_HOME = "/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home"

// Recursively find the newest image artifact created after `since`
function findLatestScreenshot(since: number): string | null {
  const roots = [
    path.join(MAVEN_PROJECT_PATH, "allure-results"),
    path.join(MAVEN_PROJECT_PATH, "target")
  ]
  let newest: { file: string; mtime: number } | null = null

  const walk = (dir: string, depth: number) => {
    if (depth > 4 || !fs.existsSync(dir)) return
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        // surefire-reports only contains tiny HTML report icons, not evidence
        if (entry.name === "surefire-reports") continue
        walk(full, depth + 1)
      } else if (/\.(png|jpg|jpeg)$/i.test(entry.name)) {
        const stat = fs.statSync(full)
        // skip icon-sized assets; real SHAFT screenshots are far larger
        if (stat.size < 5 * 1024) continue
        if (stat.mtimeMs >= since && (!newest || stat.mtimeMs > newest.mtime)) {
          newest = { file: full, mtime: stat.mtimeMs }
        }
      }
    }
  }

  roots.forEach((r) => walk(r, 0))
  return newest ? (newest as { file: string }).file : null
}

// Find the newest single-file Allure report HTML generated by SHAFT
function findLatestAllureReport(): string | null {
  const reportDir = path.join(MAVEN_PROJECT_PATH, "allure-report")
  if (!fs.existsSync(reportDir)) return null
  const htmls = fs
    .readdirSync(reportDir)
    .filter((f) => f.endsWith(".html"))
    .map((f) => ({ f, mtime: fs.statSync(path.join(reportDir, f)).mtimeMs }))
    .sort((a, b) => b.mtime - a.mtime)
  return htmls.length > 0 ? `/api/hub/allure/${htmls[0].f}` : null
}

// A remote/Docker/Grid execution target (Section 1c). `undefined` = run locally.
export interface ExecutionTargetLike {
  name: string
  type: string // "local" | "docker" | "grid" | "browserstack"
  url: string
  platform: string // "Linux" | "Windows" | "Mac"
  browser: string
  headless: boolean
}

// Map the UI platform to the SHAFT targetOperatingSystem property value
const OS_BY_PLATFORM: Record<string, string> = {
  Linux: "Linux-64",
  Windows: "Windows-64",
  Mac: "Mac-64"
}

// Upsert a single key=value into a properties file body (returns new body)
function upsertProperty(body: string, key: string, value: string): string {
  const lines = body.split("\n")
  let found = false
  const next = lines.map((line) => {
    if (line.trim().startsWith(`${key}=`) || line.trim() === key || line.trim().startsWith(`${key} `)) {
      found = true
      return `${key}=${value}`
    }
    return line
  })
  if (!found) next.push(`${key}=${value}`)
  return next.join("\n")
}

// Update custom.properties so SHAFT targets the requested browser + execution
// target, and toggles the WCAG accessibility audit (Section 1b).
function applyRunProperties(browser: string, target?: ExecutionTargetLike, accessibility = false) {
  const customPropsPath = path.join(MAVEN_PROJECT_PATH, "src/main/resources/properties/custom.properties")
  let body = fs.existsSync(customPropsPath) ? fs.readFileSync(customPropsPath, "utf8") : ""

  const remote = target && target.type !== "local"
  // A non-local target may pin its own browser; otherwise honour the toolbar choice
  const effectiveBrowser = remote && target.browser ? target.browser : browser
  const browserValue = effectiveBrowser.toLowerCase() === "headless" ? "chrome" : effectiveBrowser.toLowerCase()
  const headless = effectiveBrowser.toLowerCase() === "headless" || Boolean(target?.headless)

  body = upsertProperty(body, "targetBrowserName", browserValue)
  body = upsertProperty(body, "headlessExecution", headless ? "true" : "false")
  // executionAddress = "local" for local runs, else the grid/hub host:port
  body = upsertProperty(body, "executionAddress", remote ? target.url : "local")
  body = upsertProperty(body, "targetOperatingSystem", OS_BY_PLATFORM[target?.platform || "Linux"] || "Linux-64")
  body = upsertProperty(body, "accessibilityTesting", accessibility ? "true" : "false")

  fs.mkdirSync(path.dirname(customPropsPath), { recursive: true })
  fs.writeFileSync(customPropsPath, body, "utf8")
}

export interface HubScriptLike {
  id: string
  name: string
  type: string
  code: string
}

// Starts a Maven run in the background and returns the executionId immediately.
export async function startScriptRun(
  script: HubScriptLike,
  browser: string,
  debug = false,
  target?: ExecutionTargetLike,
  accessibility = false
): Promise<string> {
  // Write the latest code into the Maven workspace
  const javaFilePath = path.join(
    MAVEN_PROJECT_PATH,
    "src/test/java/com/ourcompany/tests",
    `${script.name}.java`
  )
  fs.mkdirSync(path.dirname(javaFilePath), { recursive: true })
  fs.writeFileSync(javaFilePath, script.code, "utf8")

  applyRunProperties(browser, target, accessibility)

  const targetLabel = target && target.type !== "local" ? target.name : "Local"
  const execution = await prisma.testExecution.create({
    data: {
      scriptId: script.id,
      status: "Running",
      logOutput: `[Test Studio] Queued ${script.name} on ${browser} · target: ${targetLabel}${debug ? " (debug mode)" : ""}...\n`,
      browser,
      executionTarget: target && target.type !== "local" ? target.name : null
    }
  })

  const started = Date.now()
  const mvnFlags = debug ? " -e" : ""
  const cmd = `JAVA_HOME=${JAVA_HOME} mvn test -Dtest=${script.name}${mvnFlags}`

  const child = spawn(cmd, { cwd: MAVEN_PROJECT_PATH, shell: true })

  let logBuffer = `[Test Studio] Queued ${script.name} on ${browser} · target: ${targetLabel}${debug ? " (debug mode)" : ""}...\n`
  let lastFlush = 0
  let flushing = false

  const flushLogs = async (force = false) => {
    if (flushing) return
    if (!force && Date.now() - lastFlush < 1000) return
    flushing = true
    lastFlush = Date.now()
    try {
      await prisma.testExecution.update({
        where: { id: execution.id },
        data: { logOutput: logBuffer }
      })
    } catch {
      // execution may have been deleted mid-run; ignore
    } finally {
      flushing = false
    }
  }

  child.stdout.on("data", (d) => {
    logBuffer += d.toString()
    flushLogs()
  })
  child.stderr.on("data", (d) => {
    logBuffer += d.toString()
    flushLogs()
  })

  child.on("error", async (err) => {
    logBuffer += `\n[Test Studio] Failed to spawn Maven: ${err.message}\n`
    try {
      await prisma.testExecution.update({
        where: { id: execution.id },
        data: { status: "Failed", logOutput: logBuffer, duration: Date.now() - started }
      })
    } catch {}
  })

  child.on("close", async (code) => {
    const failed =
      code !== 0 ||
      logBuffer.includes("BUILD FAILURE") ||
      logBuffer.includes("COMPILATION ERROR") ||
      logBuffer.includes("Failures: 1")

    const screenshotPath = findLatestScreenshot(started)
    const allureLink = findLatestAllureReport()

    try {
      await prisma.testExecution.update({
        where: { id: execution.id },
        data: {
          status: failed ? "Failed" : "Passed",
          logOutput: logBuffer,
          duration: Date.now() - started,
          screenshotPath,
          allureLink
        }
      })

      // Register run artifacts (screenshots, videos, logs, HAR) in the Evidence Vault
      await harvestEvidence({
        executionId: execution.id,
        since: started,
        status: failed ? "fail" : "pass",
        scriptName: script.name,
        scriptType: script.type,
        browser,
        targetUrl: extractTargetUrl(script.code)
      })

      // Parse & store WCAG accessibility audit results when enabled (Section 1b)
      if (accessibility) {
        await parseAndStoreAccessibility({ executionId: execution.id, scriptId: script.id, since: started })
      }
    } catch {}
  })

  return execution.id
}
