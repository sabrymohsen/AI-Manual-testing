// Bundles the plain-English step runner into one CommonJS file (qa-steps.cjs)
// that generated Automation Hub tests require, and stores it as a string in
// src/lib/plain-english/runtime/qa-steps-runtime.generated.ts.
//   npm run gen:steps-runtime          write it
//   node scripts/build-steps-runtime.mjs --print   print the bundle (used by the staleness test)
import { build } from "esbuild"
import { writeFileSync } from "fs"
import path from "path"
import { fileURLToPath } from "url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")

export async function bundle() {
  const res = await build({
    entryPoints: [path.join(root, "src/lib/plain-english/runtime/entry.ts")],
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node18",
    write: false,
    legalComments: "none",
    external: ["playwright", "@playwright/test"],
    alias: { "@": path.join(root, "src") },
    plugins: [
      {
        // Visual checkpoints save to QA Engine's database; generated tests use
        // Playwright's toHaveScreenshot instead, so this import is never reached.
        name: "no-server-modules",
        setup(b) {
          b.onResolve({ filter: /visual-tests\/checkpoint$/ }, () => ({ path: "checkpoint", namespace: "stub" }))
          b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({
            contents: "export async function captureFlowCheckpoint() { throw new Error('Use a Playwright screenshot check here') }",
            loader: "js",
          }))
        },
      },
    ],
  })
  return "// qa-steps.cjs — QA Engine plain-English step runner (generated; do not edit).\n" + res.outputFiles[0].text
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const code = await bundle()
  if (process.argv.includes("--print")) {
    process.stdout.write(code)
  } else {
    const out = path.join(root, "src/lib/plain-english/runtime/qa-steps-runtime.generated.ts")
    writeFileSync(out, `// Generated by scripts/build-steps-runtime.mjs — do not edit.\nexport const QA_STEPS_RUNTIME = ${JSON.stringify(code)}\n`)
    console.log(`wrote ${path.relative(root, out)} (${(code.length / 1024).toFixed(1)} KB)`)
  }
}
